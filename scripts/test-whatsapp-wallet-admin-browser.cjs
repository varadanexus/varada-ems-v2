    const activation=await page.evaluate(()=>window.testCalls.find(c=>c.action==='staff_wallet_set_activation'));
    assert.deepEqual(activation.body,{tenantId:'tenant-a',enabled:true,reason:'Isolated Live activation browser fixture',evidenceReference:'release-review-fixture-001',confirmed:true});
