import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const source=await readFile(new URL('../new-ems/shared/whatsapp-wallet-view.js',import.meta.url),'utf8');
const {walletMoney,walletCsv,walletMinorMoney,rechargeHistoryRow}=await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
assert.equal(walletMinorMoney(120785,'INR',2),'INR 1207.85');
assert.equal(walletMinorMoney(null,'INR',2),'INR —');
assert.equal(walletMinorMoney(0,'INR',2),'INR 0.00');
assert.equal(walletMinorMoney(100,'INR',undefined),'INR —');
const recharge={credit_amount_minor:100000,amount_minor:120785,charge_breakdown:{serviceGstMinor:18000,gatewayFeeMinor:2360,gatewayGstMinor:425,policyId:'fixture-v1'}};
const flat=rechargeHistoryRow(recharge);
assert.equal(flat.service_gst_minor,18000);
assert.equal(flat.gateway_gst_minor,425);
assert.equal(flat.charge_policy_id,'fixture-v1');
assert.equal(rechargeHistoryRow({}).gateway_fee_minor,null);
assert.ok(walletCsv([flat],['credit_amount_minor','service_gst_minor','gateway_fee_minor','gateway_gst_minor','amount_minor']).includes('"100000","18000","2360","425","120785"'));
assert.equal(walletMoney('3500'),'USD 0.0035');
assert.equal(walletMoney('-700'),'USD -0.0007');
assert.equal(walletMoney('291375','INR'),'INR 0.291375');
assert.equal(walletMoney('9007199254740991000','INR'),'INR 9007199254740.991');
assert.equal(walletMoney('bad'),'USD —');
const csv=walletCsv([{id:'=HYPERLINK("bad")',note:'line1\nline2',currency:'INR'}],['id','note','currency']);
assert.ok(csv.includes('"\'=HYPERLINK(""bad"")"'));
assert.ok(csv.includes('"line1\nline2"'));
assert.ok(csv.startsWith('\uFEFF'));
console.log('PASS: exact fractional/native-currency formatting, large integer balances, quoted CSV and formula neutralization');
